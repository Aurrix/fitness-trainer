  assert.notEqual(await coverage.locator('tbody').innerText(), allText)
  assert.ok((await coverage.locator('tbody td:last-child').allTextContents()).every(text => text === '1 / 1 sessions'))
  await coverage.getByRole('checkbox', { name: 'Primary targets only' }).check()
  await coverage.getByRole('button', { name: 'Sessions', exact: true }).click()
  await coverage.locator('tbody button').first().click()
  await coverage.getByRole('button', { name: 'Clear muscle selection' }).waitFor()
  await page.screenshot({ path: '.tmp/program-library/coverage-mobile.png' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
