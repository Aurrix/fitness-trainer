  console.log('Checking mobile filters')
  await openFilters()
  let dialog = page.getByRole('dialog', { name: 'Filter programs' })
  await dialog.getByRole('group', { name: 'Days per week', exact: true }).getByRole('button', { name: '4', exact: true }).click()
  await dialog.getByRole('group', { name: 'Split type', exact: true }).getByRole('button', { name: 'Upper / Lower', exact: true }).click()
  await dialog.getByRole('button', { name: /^Show \d+ programs?$/ }).click()
  assert.ok(await page.locator('.program-card').count() > 0)
  const metadata = await page.locator('.program-card__meta').allTextContents()
  assert.ok(metadata.every(text => text.includes('4 days / week') && text.includes('Upper / Lower')))
  await openFilters()
  dialog = page.getByRole('dialog', { name: 'Filter programs' })
  await dialog.getByRole('group', { name: 'Days per week', exact: true }).getByRole('button', { name: '7', exact: true }).click()
