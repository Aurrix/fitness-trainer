  const footer = fullBodyDialog.locator('.program-detail-footer')
  await fullBodyDialog.locator('.program-detail-content').evaluate(element=>{element.scrollTop=element.scrollHeight})
  assert.ok(await footer.getByRole('button',{name:'Start first day',exact:true}).isVisible())
  const footerBounds=await footer.boundingBox(),dialogBounds=await fullBodyDialog.boundingBox()
  assert.ok(footerBounds.y+footerBounds.height<=dialogBounds.y+dialogBounds.height+1)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  assert.deepEqual(errors, [])
  console.log('Passed mobile filter apply/cancel/clear, weekly schedule metadata, sorting, muscle period/session/primary controls, muscle selection, and viewport checks.')
