  await dayOverview.locator('.program-day-card__exercise-link').first().click()
  await page.locator('.overlay').last().getByRole('button', { name: 'Close', exact: true }).click()
  await programDialog.getByRole('button', { name: 'Close', exact: true }).click()
  await card.getByRole('button', { name: /View muscle coverage/ }).click()
  console.log('Checking muscle coverage')
  const coverage = page.getByRole('region', { name: 'Program muscle coverage' })
  await coverage.getByRole('heading', { name: 'What this plan trains' }).waitFor()
  assert.equal(await coverage.getByRole('combobox', { name: 'Coverage period' }).inputValue(), '1')
  const rows = coverage.locator('tbody tr')
  assert.ok(await rows.count() > 5)
  const chestRow = coverage.getByRole('row', { name: /^Chest\b/ })
  const metricSummary = coverage.locator('.program-coverage-metric-summary')
  assert.equal(await coverage.locator('table').getAttribute('data-metric'), 'sets')
  assert.ok((await metricSummary.innerText()).includes('Planned sets per muscle'))
  const setsText = await chestRow.locator('td').innerText()
  assert.match(setsText, /sets/)
  await coverage.getByRole('button', { name: 'Exercises', exact: true }).click()
  assert.equal(await coverage.locator('table').getAttribute('data-metric'), 'exercises')
  const exercisesText = await chestRow.locator('td').innerText()
  assert.match(exercisesText, /exercise slots/)
  assert.notEqual(exercisesText, setsText)
  assert.ok((await metricSummary.innerText()).includes('Exercise slots per muscle'))
  await coverage.getByRole('button', { name: 'Sessions', exact: true }).click()
  const sessionsText = await chestRow.locator('td').innerText()
  assert.match(sessionsText, /\d+ \/ 4 sessions/)
  assert.notEqual(sessionsText, exercisesText)
  assert.ok((await metricSummary.innerText()).includes('Sessions per muscle'))
  await coverage.getByRole('button', { name: 'Planned sets', exact: true }).click()
  assert.equal(await chestRow.locator('td').innerText(), setsText)
  await coverage.getByRole('button', { name: 'Sessions', exact: true }).click()
  const allText = await coverage.locator('tbody').innerText()
