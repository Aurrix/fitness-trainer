  await page.getByRole('combobox', { name: 'Sort programs' }).selectOption('name')
  const titles = await page.locator('.program-card h3').allTextContents()
  assert.deepEqual(titles, [...titles].sort((a, b) => a.localeCompare(b)))
  fs.mkdirSync('.tmp/program-library', { recursive: true })
  await page.screenshot({ path: '.tmp/program-library/filtered-mobile.png' })
  await page.getByRole('button', { name: 'Clear all', exact: true }).click()
  await page.getByRole('searchbox').fill('PHUL — Liftosaur')
  const card = page.locator('.program-card').filter({ has: page.getByRole('heading', { name: 'PHUL — Liftosaur', exact: true }) })
  const overview = card.getByRole('group', { name: 'PHUL — Liftosaur muscle overview', exact: true })
  await overview.scrollIntoViewIfNeeded()
  await overview.locator('svg').first().waitFor()
  assert.equal(await overview.locator('svg').count(), 2)
  assert.equal(await overview.locator('li').count(), 4)
  assert.ok((await overview.innerText()).includes('Week 1 · 4 sessions'))
  await overview.getByRole('button', { name: /more muscle groups/ }).click()
  assert.ok(await overview.locator('li').count() > 4)
  await overview.getByRole('button', { name: 'Show main groups', exact: true }).click()
  assert.equal(await overview.locator('li').count(), 4)
  await card.screenshot({ path: '.tmp/program-library/card-muscle-overview.png' })
  await page.unroute('**/*')
  await card.getByRole('button', { name: 'Open', exact: true }).click()
  const programDialog = page.getByRole('dialog', { name: 'PHUL — Liftosaur', exact: true })
  assert.equal(await programDialog.locator('.program-detail-actions').count(), 0)
  await programDialog.getByRole('button', { name: 'Start first day', exact: true }).waitFor()
  const saveProgram = programDialog.getByRole('button', { name: /^(Save program|Remove saved program)$/ })
  const initiallySaved = await saveProgram.getAttribute('aria-pressed')
  await saveProgram.click()
  assert.notEqual(await saveProgram.getAttribute('aria-pressed'), initiallySaved)
  await saveProgram.click()
  assert.equal(await saveProgram.getAttribute('aria-pressed'), initiallySaved)
  const moreActions = programDialog.locator('summary[aria-label="More program actions"]')
  assert.equal(await programDialog.getByRole('button', { name: 'Clone', exact: true }).count(), 0)
  await moreActions.click()
  assert.ok(await programDialog.getByRole('button', { name: 'Clone', exact: true }).isVisible())
  await page.keyboard.press('Escape')
  assert.equal(await programDialog.locator('.program-detail-menu').getAttribute('open'), null)
  await programDialog.getByRole('tab', {name:'Days & exercises'}).focus()
  await page.keyboard.press('ArrowRight')
  assert.equal(await programDialog.getByRole('tab',{name:'Muscle coverage'}).getAttribute('aria-selected'),'true')
  await page.keyboard.press('ArrowLeft')
  const dayOverview = programDialog.getByRole('region', { name: 'Day by day overview' })
  await dayOverview.getByRole('heading', { name: 'Day by day', exact: true }).waitFor()
